def download_file(url, destination):
    """Save a file and return its SHA-256 digest.

    A file on the Hub goes with the token in HF_TOKEN, if any, as gated
    datasets require; the token is not passed on to where the Hub redirects.
    """
    request = urllib.request.Request(url)
    if os.environ.get("HF_TOKEN") and url.startswith("https://huggingface.co/"):
        request.add_unredirected_header("Authorization", f"Bearer {os.environ['HF_TOKEN']}")
    digest = hashlib.sha256()
    with (
        urllib.request.urlopen(request, timeout=120) as response,
        Path(destination).open("wb") as target,
    ):
        for chunk in iter(lambda: response.read(1024 * 1024), b""):
            digest.update(chunk)
            target.write(chunk)
    return digest.hexdigest()


def slips_into_chinese(messages):
    """Whether a user's or assistant's words hold two characters that only Chinese writes."""
    return any(
        len(CHINESE.findall(message["content"])) >= 2 for message in messages if message["role"] in ("user", "assistant")
    )


def read_records(path, name):
    if name.endswith(".parquet"):
        from pyarrow import parquet

        for batch in parquet.ParquetFile(path).iter_batches(batch_size=1024):
            yield from batch.to_pylist()
    else:
        with Path(path).open(encoding="utf-8") as source:
            for line in source:
                if line.strip():
                    yield json.loads(line)


def fetch_instructions(output):
    try:
        import pyarrow  # noqa: F401
    except ImportError as error:
        raise ValueError("Install corpus dependencies with --extra corpus") from error
    output = Path(output)
    if output.exists():
        raise ValueError("output already exists; select a new instruction directory")
    output.parent.mkdir(parents=True, exist_ok=True)
    staging = Path(tempfile.mkdtemp(prefix=f".{output.name}-", dir=output.parent))
    try:
        manifest = {
            "version": 1,
            "retrieved_at": datetime.now(UTC).isoformat(),
            "sources": {},
            "files": {},
        }
        counts = dict.fromkeys(LANGUAGES, 0)
        downloads = staging / "downloads"
        downloads.mkdir()
        destinations = {
            language: (staging / f"{language}.jsonl").open("w", encoding="utf-8")
            for language in LANGUAGES
        }
        try:
            for name, source in SOURCES.items():
                kept = malformed = unselected = chinese = too_long = 0
                # The sample keeps the conversations with the smallest digests
                # of their place in the pinned files, as negated keys in a heap.
                sample = []
                for path, expected in source["files"].items():
                    download = downloads / expected
                    if not download.exists() and (
                        download_file(SOURCE_URL.format(path=path, **source), download)
                        != expected
                    ):
                        raise ValueError(
                            f"{name} source checksum does not match: {path}"
                        )
                    for index, record in enumerate(read_records(download, path)):
                        if any(record.get(field) not in values for field, values in source.get("select", {}).items()):
                            unselected += 1
                            continue
                        messages = normalize_messages(
                            source_messages(source["layout"], record)
                        )
                        if messages is None:
                            malformed += 1
                            continue
                        if source["language"] == "ja" and slips_into_chinese(messages):
                            chinese += 1
                            continue
                        if len(conversation_text(messages)[0]) > source.get("max_characters", float("inf")):
                            too_long += 1
                            continue
                        line = json.dumps({"source": name, "messages": messages}, ensure_ascii=False) + "\n"
                        if "limit" not in source:
                            destinations[source["language"]].write(line)
                            kept += 1
                            continue
                        key = int(hashlib.sha256(f"{name}\0{path}\0{index}".encode()).hexdigest(), 16)
                        heapq.heappush(sample, (-key, line))
                        if len(sample) > source["limit"]:
                            heapq.heappop(sample)
                for _, line in sorted(sample, reverse=True):
                    destinations[source["language"]].write(line)
                    kept += 1
                manifest["sources"][name] = {
                    **source,
                    "dataset_url": f"https://huggingface.co/datasets/{source['repository']}",
                    "conversations": kept,
                    "malformed": malformed,
                    "unselected": unselected,
                    "chinese": chinese,
                    "too_long": too_long,
                }
                counts[source["language"]] += kept
        finally:
            for destination in destinations.values():
                destination.close()
        shutil.rmtree(downloads)
        for language in LANGUAGES:
            if not counts[language]:
                raise ValueError(f"no {language} conversations were retrieved")
            filename = f"{language}.jsonl"
            manifest["files"][filename] = {
                "conversations": counts[language],
                "sha256": file_digest(staging / filename),
            }
        (staging / "sources.json").write_text(
            json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
        )
        os.rename(staging, output)
        return manifest
    finally:
        if staging.exists():
            shutil.rmtree(staging)


def contamination_text(text):
    return re.sub(r"[\W_]+", "", unicodedata.normalize("NFKC", text).casefold())


