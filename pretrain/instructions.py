def normalize_turn(message):
    """Return a turn's normalized fields, or None if it is malformed or empty.

    A system turn may offer tools, each a name with an optional description
    and argument schema. An assistant turn may carry its reasoning and the
    tool calls it ends with, each a name and its arguments.
    """
    if (
        not isinstance(message, dict)
        or message.get("role") not in ROLES
        or not isinstance(message.get("content"), str)
    ):
        return None
    turn = {"role": message["role"], "content": unicodedata.normalize("NFC", message["content"]).strip()}
    if message["role"] == "system":
        tools = message.get("tools") or []
        if not isinstance(tools, list) or not all(
            isinstance(tool, dict)
            and isinstance(tool.get("name"), str)
            and tool["name"]
            and isinstance(tool.get("description", ""), str)
            and isinstance(tool.get("parameters", {}), dict)
            for tool in tools
        ):
            return None
        if tools:
            turn["tools"] = [
                {key: tool[key] for key in ("name", "description", "parameters") if key in tool} for tool in tools
            ]
    if message["role"] == "assistant":
        reasoning = message.get("reasoning")
        if reasoning is not None and not isinstance(reasoning, str):
            return None
        if reasoning and (reasoning := unicodedata.normalize("NFC", reasoning).strip()):
            turn["reasoning"] = reasoning
        calls = message.get("tool_calls") or []
        if not isinstance(calls, list) or not all(
            isinstance(call, dict) and isinstance(call.get("name"), str) and isinstance(call.get("arguments"), dict)
            for call in calls
        ):
            return None
        if calls:
            turn["tool_calls"] = [{"name": call["name"], "arguments": call["arguments"]} for call in calls]
    return turn if turn["content"] or turn.get("tool_calls") or turn.get("tools") else None


def normalize_messages(messages):
    """Return nonempty turns from the user to a final reply, or None.

    The user and the assistant take turns, except that tool turns return the
    results of an assistant turn's tool calls before the assistant goes on.
    """
    if not isinstance(messages, list):
        return None
    turns = [normalize_turn(message) for message in messages]
    if not all(turns):
        return None
    while turns and turns[-1]["role"] != "assistant":
        turns.pop()
    start = 1 if turns and turns[0]["role"] == "system" else 0
    if len(turns) - start < 2:
        return None
    expected = ("user",)
    for turn in turns[start:]:
        if turn["role"] not in expected:
            return None
        expected = {
            "user": ("assistant",),
            "assistant": ("tool",) if turn.get("tool_calls") else ("user",),
            "tool": ("tool", "assistant"),
        }[turn["role"]]
    return turns


def dolly_messages(record):
    instruction, context, response = (
        record.get(name) for name in ("instruction", "context", "response")
    )
    if not all(isinstance(value, str) for value in (instruction, response)):
        return None
    prompt = instruction.strip()
    if isinstance(context, str) and context.strip():
        prompt += "\n\n" + context.strip()
    return [
        {"role": "user", "content": prompt},
        {"role": "assistant", "content": response},
    ]


THINK_BLOCK = re.compile(r"\s*<think>(.*?)</think>\s*", re.DOTALL)


def tool_definition(tool):
    """A tool's name, description and argument schema, from OpenAI's layout or a bare definition."""
    function = tool.get("function", tool) if isinstance(tool, dict) else None
    if not isinstance(function, dict):
        return None
    return {key: function[key] for key in ("name", "description", "parameters") if key in function}


def nemotron_messages(record):
    """Nemotron's turns: reasoning in a leading think block, calls with JSON-encoded arguments, tools in the metadata.

    The empty system turn that version 2's conversations open with is left out.
    """
    try:
        tools = json.loads(record.get("metadata") or "{}").get("tools")
        messages = [{"role": "system", "content": "", "tools": [tool_definition(tool) for tool in tools]}] if tools else []
        for message in record["messages"]:
            if message["role"] == "system" and not message["content"].strip():
                continue
            turn = {"role": message["role"], "content": message["content"]}
            if turn["role"] == "assistant":
                thought = THINK_BLOCK.match(turn["content"])
                if thought:
                    turn["reasoning"], turn["content"] = thought.group(1), turn["content"][thought.end():]
                if "<think>" in turn["content"] or "</think>" in turn["content"]:
                    return None
                turn["tool_calls"] = [
                    {"name": call["function"]["name"], "arguments": json.loads(call["function"]["arguments"])}
                    for call in message.get("tool_calls") or ()
                ]
            messages.append(turn)
    except (AttributeError, KeyError, TypeError, ValueError):
        return None
    return messages


FUNCTION_CALL = re.compile(
    r'<functioncall>\s*\{"name":\s*"([^"]+)",\s*"arguments":\s*\'(.*)\'\s*\}\s*</functioncall>', re.DOTALL
)


def system_tools(text):
    """Split a system text into what precedes its tool definitions, JSON objects that open lines, and the tools."""
    decoder = json.JSONDecoder()
    tools, end, preamble = [], 0, None
    for match in re.finditer(r"(?m)^\{", text):
        if match.start() < end:
            continue
        if preamble is None:
            preamble = text[: match.start()].strip().removesuffix("-").strip()
        tool, end = decoder.raw_decode(text, match.start())
        tools.append(tool_definition(tool))
    # Without tools the text stays whole; with them, the instructions after
    # them describe another format's call syntax.
    return (text if preamble is None else preamble), tools


def functioncall_messages(record):
    """DataPilot's turns: tools as JSON objects in the system text, each call in a functioncall tag.

    A call that follows the assistant's own words, as a turn of its own,
    joins them in one reply.
    """
    try:
        messages = []
        for message in record["messages"]:
            turn = {"role": message["role"], "content": message["content"]}
            if turn["role"] == "system":
                turn["content"], tools = system_tools(turn["content"])
                if tools:
                    turn["tools"] = tools
            elif turn["role"] == "assistant" and "<functioncall>" in turn["content"]:
                call = FUNCTION_CALL.fullmatch(turn["content"].strip())
                if call is None:
                    return None
                turn = {
                    "role": "assistant",
                    "content": "",
                    "tool_calls": [{"name": call.group(1), "arguments": json.loads(call.group(2))}],
                }
                if messages and messages[-1]["role"] == "assistant" and "tool_calls" not in messages[-1]:
                    turn["content"] = messages.pop()["content"]
            messages.append(turn)
    except (AttributeError, KeyError, TypeError, ValueError):
        return None
    return messages


