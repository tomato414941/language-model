# A conversation containing the middle of a benchmark question is dropped.
KEY_WIDTH = {"ja": 12, "en": 24}
QUESTION_WRAPPER = re.compile(r"^(?:Question:|質問：)\s*|\s*(?:Answer:|回答：)$")


def normalize_messages(messages):
    """Return nonempty turns that alternate from the user to a final reply, or None."""
    if not isinstance(messages, list):
        return None
    turns = []
    for message in messages:
        if (
            not isinstance(message, dict)
            or message.get("role") not in ROLE_LABELS
            or not isinstance(message.get("content"), str)
        ):
            return None
        content = unicodedata.normalize("NFC", message["content"]).strip()
        if not content:
            return None
        turns.append({"role": message["role"], "content": content})
    while turns and turns[-1]["role"] != "assistant":
        turns.pop()
    start = 1 if turns and turns[0]["role"] == "system" else 0
    roles = [turn["role"] for turn in turns[start:]]
    if len(roles) < 2 or roles != ["user", "assistant"] * (len(roles) // 2):
        return None
    return turns


def source_messages(layout, record):
    if layout != "dolly":
        return record.get(layout)
    instruction, context, response = (
        record.get(name) for name in ("instruction", "context", "response")
    )
    if not all(isinstance(value, str) for value in (instruction, response)):
        return None
    prompt = instruction.strip()
    if isinstance(context, str) and context.strip():
        prompt += "\n\n" + context.strip()
    return [
        {"role": "user", "content": prompt},
        {"role": "assistant", "content": response},
    ]


def download_file(url, destination):
    digest = hashlib.sha256()
    with (
        urllib.request.urlopen(url, timeout=120) as response,
        Path(destination).open("wb") as target,
    ):
        for chunk in iter(lambda: response.read(1024 * 1024), b""):
            digest.update(chunk)
            target.write(chunk)
    return digest.hexdigest()


def read_records(path, name):
    if name.endswith(".parquet"):
        from pyarrow import parquet

        for batch in parquet.ParquetFile(path).iter_batches(batch_size=1024):
            yield from batch.to_pylist()
    else:
        with Path(path).open(encoding="utf-8") as source:
            for line in source:
                if line.strip():
                    yield json.loads(line)


def fetch_instructions(output):
    try:
        import pyarrow  # noqa: F401
    except ImportError as error:
        raise ValueError("Install corpus dependencies with --extra corpus") from error
    output = Path(output)
    if output.exists():
        raise ValueError("output already exists; select a new instruction directory")
    output.parent.mkdir(parents=True, exist_ok=True)
    staging = Path(tempfile.mkdtemp(prefix=f".{output.name}-", dir=output.parent))
    try:
        manifest = {
            "version": 1,
            "retrieved_at": datetime.now(UTC).isoformat(),
            "sources": {},
            "files": {},
        }
        counts = dict.fromkeys(LANGUAGES, 0)
        destinations = {
            language: (staging / f"{language}.jsonl").open("w", encoding="utf-8")
            for language in LANGUAGES
        }
        try:
            for name, source in SOURCES.items():
                kept = malformed = 0
                for path, expected in source["files"].items():
                    download = staging / "download"
                    if (
                        download_file(SOURCE_URL.format(path=path, **source), download)
                        != expected
                    ):
                        raise ValueError(
                            f"{name} source checksum does not match: {path}"
                        )
                    for record in read_records(download, path):
                        messages = normalize_messages(
                            source_messages(source["layout"], record)
                        )
                        if messages is None:
                            malformed += 1
                            continue
                        destinations[source["language"]].write(
                            json.dumps(
                                {"source": name, "messages": messages},
                                ensure_ascii=False,
                            )
                            + "\n"
                        )
                        kept += 1
                    download.unlink()
                manifest["sources"][name] = {
                    **source,
                    "dataset_url": f"https://huggingface.co/datasets/{source['repository']}",
                    "conversations": kept,
                    "malformed": malformed,
                }
                counts[source["language"]] += kept
        finally:
            for destination in destinations.values():
                destination.close()
        for language in LANGUAGES:
            if not counts[language]:
                raise ValueError(f"no {language} conversations were retrieved")
            filename = f"{language}.jsonl"
            manifest["files"][filename] = {
                "conversations": counts[language],
                "sha256": file_digest(staging / filename),
            }
        (staging / "sources.json").write_text(
            json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
        )
        os.rename(staging, output)
        return manifest
    finally:
        if staging.exists():
            shutil.rmtree(staging)


def contamination_text(text):
    return re.sub(r"[\W_]+", "", unicodedata.normalize("NFKC", text).casefold())


def benchmark_keys(path):
    sources = json.loads((Path(path) / "sources.json").read_text(encoding="utf-8"))
    keys = {language: set() for language in LANGUAGES}
    for name, items in load_benchmarks(path).items():
        language = sources["tasks"][name]["language"]
        width = KEY_WIDTH[language]
        for item in items:
            text = contamination_text(QUESTION_WRAPPER.sub("", item["context"]))
            if len(text) >= width:
                middle = (len(text) - width) // 2
                keys[language].add(text[middle : middle + width])
    return keys


def contaminated(messages, keys, width):
    if not keys:
        return False
    text = contamination_text(
        "\n".join(turn["content"] for turn in messages if turn["role"] != "assistant")
    )
    return any(text[i : i + width] in keys for i in range(len(text) - width + 1))


def encode_conversations(tokenizer, conversations):
    """Encode transcripts and mark the reply and final end tokens to predict."""
    bos, eos = tokenizer.token_to_id(BOS), tokenizer.token_to_id(EOS)
    texts, replies = zip(*(conversation_text(messages) for messages in conversations))
    examples = []
    for encoding, spans in zip(
        tokenizer.encode_batch(list(texts), add_special_tokens=False), replies
    ):
        starts = np.asarray([start for start, _ in encoding.offsets], dtype=np.int64)
        learn = np.zeros(len(starts), dtype=bool)
        for start, end in spans:
            learn |= (starts >= start) & (starts < end)
        examples.append(
            (
                np.asarray([bos, *encoding.ids, eos], dtype=TOKEN_DTYPE),
                np.concatenate(([0], learn, [1])).astype(MASK_DTYPE),
            )
        )
    return examples


def reply_lengths(mask):
    """Count the tokens of each reply from its run in the mask, without the final EOS."""
    edges = np.flatnonzero(np.diff(np.concatenate(([0], mask[:-1], [0]))))
    return edges[1::2] - edges[::2]


def pack_rows(examples, width, open_limit=64):
    """Place whole conversations in fixed-width rows so none is cut at a row edge."""
    rows = []
    for example in examples:
        length = len(example[0])
        for row in rows:
            if row[0] + length <= width:
                row[0] += length
                row[1].append(example)
                break
        else:
            rows.append([length, [example]])
            if len(rows) > open_limit:
                yield rows.pop(max(range(len(rows)), key=lambda i: rows[i][0]))[1]
    for _, row in rows:
        yield row


def write_rows(examples, width, eos, tokens_path, mask_path):
    rows = targets = 0
    with tokens_path.open("wb") as tokens_file, mask_path.open("wb") as mask_file:
        for row in pack_rows(examples, width):
            # End tokens pad the tail, and their zero mask keeps them out of the loss.
            tokens = np.full(width, eos, dtype=TOKEN_DTYPE)
            mask = np.zeros(width, dtype=MASK_DTYPE)
            position = 0
            for example_tokens, example_mask in row:
                tokens[position : position + len(example_tokens)] = example_tokens
                mask[position : position + len(example_mask)] = example_mask
                position += len(example_tokens)
            tokens_file.write(tokens.tobytes())
            mask_file.write(mask.tobytes())
            rows += 1
            targets += int(mask.sum())
    return rows, targets


def prepare_instructions(
    source,
    output,
    tokenizer_path,
    context=2048,
    validation_conversations=1000,
    tokens_per_language=None,
    benchmarks=None,
    seed=42,
    max_reply_tokens=None,
):
    for name, value in (
        ("context", context),
        ("validation_conversations", validation_conversations),
    ):
        if type(value) is not int or value <= 0:
            raise ValueError(f"{name} must be a positive integer")
    for name, value in (
        ("tokens_per_language", tokens_per_language),
        ("max_reply_tokens", max_reply_tokens),
    ):
        if value is not None and (type(value) is not int or value <= 0):
            raise ValueError(f"{name} must be a positive integer")
    source, output = Path(source), Path(output)
    if output.exists():
        raise ValueError("output already exists; select a new dataset directory")
    provenance = json.loads((source / "sources.json").read_text(encoding="utf-8"))
    for language in LANGUAGES:
        filename = f"{language}.jsonl"
        if file_digest(source / filename) != provenance["files"][filename]["sha256"]:
            raise ValueError(
                "instruction source checksum does not match the provenance"
            )
    tokenizer = Tokenizer.from_file(str(tokenizer_path))
    eos = tokenizer.token_to_id(EOS)
    if eos is None or tokenizer.token_to_id(BOS) is None:
        raise ValueError("the tokenizer needs BOS and EOS tokens")
    keys = benchmark_keys(benchmarks) if benchmarks is not None else {}
    output.parent.mkdir(parents=True, exist_ok=True)
    staging = Path(tempfile.mkdtemp(prefix=f".{output.name}-", dir=output.parent))
    try:
        shutil.copyfile(tokenizer_path, staging / "tokenizer.json")
        manifest = {
            "version": 1,
            "kind": "instructions",
            "dtype": TOKEN_DTYPE.str,
            "context": context,
            "seed": seed,
            "vocabulary_size": tokenizer.get_vocab_size(),
            "tokenizer_sha256": file_digest(staging / "tokenizer.json"),
            "format": "Responses API transcript; loss on assistant replies and the final EOS",
            "provenance": provenance,
            "benchmarks_sha256": file_digest(Path(benchmarks) / "sources.json")
            if benchmarks is not None
            else None,
            "validation_conversations": validation_conversations,
            "tokens_per_language": tokens_per_language,
            "max_reply_tokens": max_reply_tokens,
            "conversations": {},
            "files": {},
        }
        seen = set()
        for language in LANGUAGES:
            stats = dict.fromkeys(
                (
                    "malformed",
                    "duplicates",
                    "contaminated",
                    "too_long",
                    "long_replies",
                    "unused",
                ),
                0,
            )
            conversations = {}
            with (source / f"{language}.jsonl").open(encoding="utf-8") as lines:
                for line in lines:
                    if not line.strip():
                        continue
                    messages = normalize_messages(json.loads(line).get("messages"))
                    if messages is None:
                        stats["malformed"] += 1
                        continue
                    text = " ".join(conversation_text(messages)[0].split())
                    digest = hashlib.sha256(f"{seed}\0{text}".encode()).hexdigest()
                    if digest in seen:
                        stats["duplicates"] += 1
                        continue
                    seen.add(digest)
                    conversations[digest] = messages
            # Seeded digests give a reproducible random order for the split and budget.
            ordered = [conversations[digest] for digest in sorted(conversations)]
            del conversations
            splits = {"validation": [], "train": []}
            train_tokens = 0
            for start in range(0, len(ordered), 1024):
                if (
                    tokens_per_language is not None
                    and train_tokens >= tokens_per_language
                ):
                    stats["unused"] += len(ordered) - start
                    break
                chunk = [
                    messages
                    for messages in ordered[start : start + 1024]
                    if not contaminated(
                        messages, keys.get(language), KEY_WIDTH[language]
                    )
                ]
                stats["contaminated"] += len(ordered[start : start + 1024]) - len(chunk)
                for example in encode_conversations(tokenizer, chunk) if chunk else []:
                    if len(example[0]) > context + 1:
                        stats["too_long"] += 1
                    elif (
                        max_reply_tokens is not None
                        and reply_lengths(example[1]).max() > max_reply_tokens
                    ):
                        stats["long_replies"] += 1
                    elif len(splits["validation"]) < validation_conversations:
                        splits["validation"].append(example)
                    elif (
                        tokens_per_language is None
                        or train_tokens < tokens_per_language
                    ):
                        splits["train"].append(example)
                        train_tokens += len(example[0])
                    else:
                        stats["unused"] += 1
            for split, examples in splits.items():
                if not examples:
                    raise ValueError(f"{language} has no {split} conversations")
                filename = f"{split}_{language}"
                rows, targets = write_rows(
                    examples,
                    context + 1,
                    eos,
                    staging / f"{filename}.bin",
                    staging / f"{filename}_mask.bin",
                )
                manifest["files"][f"{filename}.bin"] = {
                    "rows": rows,
                    "tokens": rows * (context + 1),
                    "target_tokens": targets,
                    "conversations": len(examples),
                    "sha256": file_digest(staging / f"{filename}.bin"),
                }
                manifest["files"][f"{filename}_mask.bin"] = {
                    "rows": rows,
                    "sha256": file_digest(staging / f"{filename}_mask.bin"),
                }
                stats[split] = len(examples)
            manifest["conversations"][language] = stats
        (staging / "manifest.json").write_text(
            json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8"
        )
        os.rename(staging, output)
        return manifest
    finally:
        if staging.exists():
            shutil.rmtree(staging)


class InstructionCorpus:
    def __init__(self, path):
        self.path = Path(path)
        self.manifest = json.loads(
            (self.path / "manifest.json").read_text(encoding="utf-8")
        )
        if (
            self.manifest.get("version") != 1
            or self.manifest.get("kind") != "instructions"
            or self.manifest.get("dtype") != TOKEN_DTYPE.str
        ):
            raise ValueError("unsupported instruction dataset format")
        tokenizer_path = self.path / "tokenizer.json"
        if file_digest(tokenizer_path) != self.manifest["tokenizer_sha256"]:
            raise ValueError("dataset tokenizer checksum does not match")
        self.tokenizer = Tokenizer.from_file(str(tokenizer_path))
        if self.tokenizer.get_vocab_size() != self.manifest["vocabulary_size"]:
            raise ValueError("dataset vocabulary does not match the tokenizer")
        self.context = self.manifest["context"]
        width = self.context + 1
        self.rows = {}
        for split in ("train", "validation"):
            self.rows[split] = {}
            for language in LANGUAGES:
                arrays = []
                for suffix, dtype in (("", TOKEN_DTYPE), ("_mask", MASK_DTYPE)):
                    filename = f"{split}_{language}{suffix}.bin"
                    metadata = self.manifest["files"][filename]
                    path = self.path / filename
                    if path.stat().st_size != metadata["rows"] * width * dtype.itemsize:
                        raise ValueError(
                            f"dataset row count does not match: {filename}"
                        )
                    if file_digest(path) != metadata["sha256"]:
                        raise ValueError(f"dataset checksum does not match: {filename}")
                    arrays.append(
                        np.memmap(
                            path, mode="r", dtype=dtype, shape=(metadata["rows"], width)
                        )
                    )
                self.rows[split][language] = tuple(arrays)
        self.fingerprint = hashlib.sha256(
            json.dumps(self.manifest, sort_keys=True).encode()
        ).hexdigest()

    def validate_context(self, context):
        if context != self.context:
            raise ValueError(
                f"instruction rows were packed for a {self.context}-token context"
            )

    def batch(self, split, batch_size, context, generator, device, language=None):
        self.validate_context(context)
        tokens, masks = [], []
        for selected in batch_languages(batch_size, generator, language):
            rows, row_masks = self.rows[split][selected]
            index = torch.randint(len(rows), (1,), generator=generator).item()
            tokens.append(np.asarray(rows[index], dtype=np.int64))
            masks.append(np.asarray(row_masks[index], dtype=bool))
        tokens = torch.from_numpy(np.stack(tokens))
        learn = torch.from_numpy(np.stack(masks))
        # Cross-entropy ignores -100, so prompts and padding add no loss.
        targets = tokens[:, 1:].masked_fill(~learn[:, 1:], -100)
        inputs = tokens[:, :-1]
        cuda = device.type == "cuda"
        if cuda:
            inputs, targets = inputs.pin_memory(), targets.pin_memory()
        return (
            inputs.to(device, non_blocking=cuda),
            targets.to(device, non_blocking=cuda),
        )
